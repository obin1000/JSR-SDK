// C API of JSR-SDK: see include/JSR-SDK/jsr_sdk.h.
//
// This file is compiled as native code (no /clr). It wraps the DLL's internal
// C++ interface in SdkManager.hpp, which is safe here because both sides are
// built by MSVC into the same DLL. Being native keeps two things simple:
// - thread_local works (it doesn't under /clr), so the last error message is
//   kept per thread;
// - nothing managed runs while the DLL loads: the CLR only starts on the
//   first real call, such as JSR_Create.
//
// Every exported function catches every C++ exception, so none reaches the
// caller; the adapter turns managed exceptions into C++ ones first. It is
// compiled with /EHs, not /EHa, so catch (...) doesn't catch crashes
// (structured exceptions such as access violations): those end the process
// where they happened (#36).
//
// Generated by tools/gen_c_api/generate.py from templates/jsr_sdk_c.cpp.in and
// methods.py: edit those and regenerate, not this file. CI checks that it is
// up to date, and ci/check_c_api_parity.py that every SdkManager method
// has a C function.
